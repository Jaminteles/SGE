-- Fluxo de caixa consolidado (RF-101 / RF-103)
CREATE OR REPLACE VIEW vw_fluxo_caixa AS
SELECT t.empresa_id,
       t.filial_id,
       p.data_vencimento                    AS data_referencia,
       t.tipo,
       t.categoria_financeira_id,
       t.centro_custo_id,
       CASE
           WHEN p.status = 'LIQUIDADA' THEN 'REALIZADO'::enum_realizacao
           WHEN p.data_vencimento < current_date THEN 'VENCIDO'::enum_realizacao
           ELSE 'PREVISTO'::enum_realizacao
       END                                   AS situacao,
       CASE WHEN p.status = 'LIQUIDADA' THEN p.valor_liquidado ELSE p.saldo END AS valor
FROM titulo_parcela p
JOIN titulo t ON t.id = p.titulo_id
WHERE t.status <> 'CANCELADO'
  AND p.status <> 'CANCELADA';

