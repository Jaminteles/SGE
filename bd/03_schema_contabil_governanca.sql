-- RN-008: periodo fechado bloqueia lancamentos incompativeis
CREATE OR REPLACE FUNCTION fn_valida_periodo_fechado() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE v_status enum_status_periodo;
BEGIN
    SELECT p.status INTO v_status
      FROM periodo_contabil p
     WHERE p.empresa_id = NEW.empresa_id
       AND NEW.data_competencia BETWEEN p.data_inicio AND p.data_fim;

    IF v_status = 'FECHADO' THEN
        RAISE EXCEPTION 'Periodo contabil fechado para a competencia % (RN-008).', NEW.data_competencia;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_lancamento_periodo_fechado
    BEFORE INSERT OR UPDATE ON lancamento_contabil
    FOR EACH ROW EXECUTE FUNCTION fn_valida_periodo_fechado();

-- Partidas dobradas: soma de debitos = soma de creditos
CREATE OR REPLACE FUNCTION fn_valida_partidas_dobradas() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_debito  dom_valor;
    v_credito dom_valor;
    v_lanc    uuid := coalesce(NEW.lancamento_contabil_id, OLD.lancamento_contabil_id);
BEGIN
    SELECT coalesce(sum(valor) FILTER (WHERE tipo = 'DEBITO'), 0),
           coalesce(sum(valor) FILTER (WHERE tipo = 'CREDITO'), 0)
      INTO v_debito, v_credito
      FROM lancamento_partida
     WHERE lancamento_contabil_id = v_lanc;

    IF v_debito <> v_credito THEN
        RAISE EXCEPTION 'Lancamento % desbalanceado: debito % <> credito %.', v_lanc, v_debito, v_credito;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_partidas_dobradas
    AFTER INSERT OR UPDATE OR DELETE ON lancamento_partida
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_valida_partidas_dobradas();

-- Somente contas analiticas aceitam lancamento
CREATE OR REPLACE FUNCTION fn_valida_conta_analitica() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE v_aceita boolean;
BEGIN
    SELECT aceita_lancamento INTO v_aceita FROM conta_contabil WHERE id = NEW.conta_contabil_id;
    IF NOT coalesce(v_aceita, false) THEN
        RAISE EXCEPTION 'Conta contabil sintetica nao aceita lancamento direto.';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_partida_conta_analitica
    BEFORE INSERT OR UPDATE ON lancamento_partida
    FOR EACH ROW EXECUTE FUNCTION fn_valida_conta_analitica();

-- Recalculo de saldos do titulo/parcela apos baixa (RF-057 / RF-058)
CREATE OR REPLACE FUNCTION fn_recalcula_saldos_titulo() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_parcela uuid := coalesce(NEW.titulo_parcela_id, OLD.titulo_parcela_id);
    v_titulo  uuid;
BEGIN
    UPDATE titulo_parcela p
       SET valor_liquidado = sub.liquidado,
           saldo           = greatest(p.valor + p.valor_juros + p.valor_multa - p.valor_desconto - sub.liquidado, 0),
           status = CASE
                        WHEN sub.liquidado >= (p.valor + p.valor_juros + p.valor_multa - p.valor_desconto) THEN 'LIQUIDADA'::enum_status_parcela
                        WHEN sub.liquidado > 0 THEN 'PARCIALMENTE_LIQUIDADA'::enum_status_parcela
                        ELSE 'ABERTA'::enum_status_parcela
                    END,
           data_liquidacao = sub.ultima_baixa
      FROM (
            SELECT coalesce(sum(b.valor_principal + b.valor_juros + b.valor_multa - b.valor_desconto), 0) AS liquidado,
                   max(b.data_baixa) AS ultima_baixa
              FROM titulo_baixa b
             WHERE b.titulo_parcela_id = v_parcela
               AND NOT b.estornada
           ) sub
     WHERE p.id = v_parcela
    RETURNING p.titulo_id INTO v_titulo;

    UPDATE titulo t
       SET valor_liquidado = sub.liquidado,
           saldo           = greatest(t.valor_liquido - sub.liquidado, 0),
           status = CASE
                        WHEN t.status = 'CANCELADO' THEN t.status
                        WHEN sub.liquidado >= t.valor_liquido THEN 'LIQUIDADO'::enum_status_titulo
                        WHEN sub.liquidado > 0 THEN 'PARCIALMENTE_LIQUIDADO'::enum_status_titulo
                        ELSE 'ABERTO'::enum_status_titulo
                    END
      FROM (
            SELECT coalesce(sum(p.valor_liquidado), 0) AS liquidado
              FROM titulo_parcela p
             WHERE p.titulo_id = v_titulo
           ) sub
     WHERE t.id = v_titulo;

    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_recalcula_saldos_titulo
    AFTER INSERT OR UPDATE OR DELETE ON titulo_baixa
    FOR EACH ROW EXECUTE FUNCTION fn_recalcula_saldos_titulo();

-- Atualizacao de saldo de estoque a partir do movimento (RF-031 / RF-032)
CREATE OR REPLACE FUNCTION fn_aplica_movimento_estoque() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE v_delta dom_quantidade;
BEGIN
    v_delta := CASE
        WHEN NEW.tipo IN ('ENTRADA','TRANSFERENCIA_ENTRADA','AJUSTE_POSITIVO') THEN NEW.quantidade
        WHEN NEW.tipo IN ('SAIDA','TRANSFERENCIA_SAIDA','AJUSTE_NEGATIVO')     THEN -NEW.quantidade
        ELSE 0
    END;

    INSERT INTO estoque_saldo (empresa_id, produto_id, local_estoque_id, quantidade, custo_medio, valor_total)
    VALUES (NEW.empresa_id, NEW.produto_id, NEW.local_estoque_id, v_delta, NEW.custo_unitario,
            v_delta * NEW.custo_unitario)
    ON CONFLICT (produto_id, local_estoque_id) DO UPDATE
       SET quantidade    = estoque_saldo.quantidade + v_delta,
           custo_medio   = CASE
                               WHEN v_delta > 0 AND (estoque_saldo.quantidade + v_delta) > 0
                                   THEN ((estoque_saldo.quantidade * estoque_saldo.custo_medio)
                                         + (v_delta * NEW.custo_unitario))
                                        / (estoque_saldo.quantidade + v_delta)
                               ELSE estoque_saldo.custo_medio
                           END,
           valor_total   = (estoque_saldo.quantidade + v_delta) * estoque_saldo.custo_medio,
           atualizado_em = now();

    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_aplica_movimento_estoque
    AFTER INSERT ON movimento_estoque
    FOR EACH ROW EXECUTE FUNCTION fn_aplica_movimento_estoque();

