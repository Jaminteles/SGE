-- RF-118: protecao contra alteracao
CREATE OR REPLACE FUNCTION fn_bloqueia_alteracao_auditoria() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Registros de auditoria nao podem ser alterados ou removidos (RF-118).';
END;
$$;

CREATE TRIGGER trg_auditoria_imutavel
    BEFORE UPDATE OR DELETE ON auditoria
    FOR EACH ROW EXECUTE FUNCTION fn_bloqueia_alteracao_auditoria();

-- Trigger generico de auditoria (aplicar nas tabelas criticas)
CREATE OR REPLACE FUNCTION fn_auditoria_generica() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_anterior  jsonb;
    v_posterior jsonb;
    v_evento    enum_tipo_evento_auditoria;
    v_campos    text[];
    v_empresa   uuid;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_evento := 'CRIACAO';
        v_posterior := to_jsonb(NEW);
    ELSIF TG_OP = 'UPDATE' THEN
        v_evento := 'ALTERACAO';
        v_anterior := to_jsonb(OLD);
        v_posterior := to_jsonb(NEW);
        SELECT array_agg(chave)
          INTO v_campos
          FROM jsonb_each(v_posterior) AS n(chave, valor)
         WHERE v_anterior -> n.chave IS DISTINCT FROM n.valor;
    ELSE
        v_evento := 'EXCLUSAO';
        v_anterior := to_jsonb(OLD);
    END IF;

    v_empresa := coalesce((v_posterior ->> 'empresa_id')::uuid,
                          (v_anterior  ->> 'empresa_id')::uuid,
                          fn_empresa_corrente());

    INSERT INTO auditoria (empresa_id, usuario_id, evento, entidade, entidade_id,
                           valor_anterior, valor_posterior, campos_alterados,
                           origem, correlation_id)
    VALUES (v_empresa,
            fn_usuario_corrente(),
            v_evento,
            TG_TABLE_NAME,
            coalesce((v_posterior ->> 'id')::uuid, (v_anterior ->> 'id')::uuid),
            v_anterior,
            v_posterior,
            v_campos,
            coalesce(current_setting('app.origem', true), 'API'),
            current_setting('app.correlation_id', true));

    RETURN coalesce(NEW, OLD);
END;
$$;

